// Generates supabase/seed.sql from the curriculum, so the DB content always matches the code.
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { domains, validateCurriculum } from '../src/index';

const errors = validateCurriculum();
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const q = (s: string | undefined | null) => s == null ? 'null' : `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ['-- Generated by packages/engine/scripts/seed-sql.ts. Do not edit.', 'begin;'];

domains.forEach((d, i) => lines.push(`insert into domains (id, name, tagline, sort) values (${q(d.id)}, ${q(d.name)}, ${q(d.tagline)}, ${i}) on conflict (id) do update set name = excluded.name, tagline = excluded.tagline, sort = excluded.sort;`));
for (const d of domains) for (const a of d.adjacent) lines.push(`insert into domain_adjacency values (${q(d.id)}, ${q(a)}) on conflict do nothing;`);

let sort = 0;
for (const d of domains) for (const c of d.chapters) {
  lines.push(`insert into chapters (id, domain_id, title, tier, boss_brief, studio_layer, sort) values (${q(c.id)}, ${q(d.id)}, ${q(c.title)}, ${q(c.tier)}, ${q(c.boss)}, ${q(c.studio)}, ${sort++}) on conflict (id) do update set title = excluded.title, tier = excluded.tier, boss_brief = excluded.boss_brief, studio_layer = excluded.studio_layer, sort = excluded.sort;`);
}
for (const d of domains) for (const c of d.chapters) for (const p of c.prereqs) lines.push(`insert into chapter_prereqs values (${q(c.id)}, ${q(p)}) on conflict do nothing;`);
for (const d of domains) for (const c of d.chapters) c.lessons.forEach((l, i) =>
  lines.push(`insert into lessons (chapter_id, title, mechanic, sort) select ${q(c.id)}, ${q(l.title)}, ${q(l.mechanic)}, ${i} where not exists (select 1 from lessons where chapter_id = ${q(c.id)} and sort = ${i});`));

lines.push('commit;');
const out = new URL('../../../supabase/seed.sql', import.meta.url);
writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${lines.length - 3} statements to supabase/seed.sql`);
